/**
 * 「人话词典」主体（平台通用 + 回测）
 * ==================================
 * 用户原话（2026-09-29）：「回测中心对于小白来说太难用了，很多东西我都不懂，
 * 基准标的和标的我理解不了 …… 针对一些词汇都有鼠标悬浮的解释」。
 *
 * ⚠️ 这个文件原本住在 `components/backtest/glossary.ts`。做组合优化页时发现
 *    「夏普比率 / 最大回撤 / 年化波动」这类词两个页面都要用，而优化页去 import
 *    一个 `backtest/` 下的词典属于反向依赖，所以整体提升到 `components/terms/`。
 *    回测专属与优化专属的词条分别留在各自领域文件里，由 `terms/index.ts` 合并 ——
 *    **查词一律走 `terms/index.ts` 的 `term()`，不要直接 import 本文件**，
 *    否则会漏掉另一个领域的词条，表现为「有的词有解释、有的词抛错」。
 *
 * 所以这里不是把专业定义抄一遍，而是按「是什么 / 怎么看（怎么用）/ 注意」三段写：
 *   - **是什么**：用生活化类比说清它到底指什么，不出现「横截面」「夏普比率」这类
 *     需要再解释一遍的词；
 *   - **怎么看**：给出可执行的动作（填多少、先看哪个、多少算好），
 *     而不是「需结合具体情况分析」这种正确的废话；
 *   - **注意**：只写**会让人误判**的坑（如「回撤 60% 的策略实盘拿不住」）。
 *
 * ⚠️ 正文是**纯文本**（不是 Markdown），写 `**强调**` 会在气泡里原样显示星号 ——
 *    render-check 的「文案卫生」会拦截（glossary 已加入该检查清单）。
 *
 * ⚠️ 数值门槛（如夏普 > 1、|IC| ≥ 0.03）都取自本项目后端/策略实现里的既有口径，
 *    不是随手编的经验值。改门槛前先确认后端口径同步。
 */

